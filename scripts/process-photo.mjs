// Builds the portrait assets from a transparent cutout.
// Usage: node scripts/process-photo.mjs [path/to/cutout.png]   (default: public/images/me-cutout.png)
//
// Outputs (public/images):
//   hero-4x5.webp    1200x1500  hero (figure bottom-aligned, transparent headroom)
//   about-1x1.webp    800x800   About section, head and shoulders
//   og-portrait.png   480x600   source for the generated Open Graph images
import sharp from "sharp";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { writeFileSync } from "node:fs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = process.argv[2] ?? join(root, "public/images/me-cutout.png");
const out = (name) => join(root, "public/images", name);

const { width, height } = await sharp(src).metadata();

// 4:5: take the centre 90% of the width and add a little transparent headroom if needed.
const heroW = Math.round(width * 0.9);
const heroH = Math.round(heroW * 1.25);
const hero = await sharp(src)
  .extract({ left: Math.round((width - heroW) / 2), top: 0, width: heroW, height })
  .extend({ top: Math.max(0, heroH - height), background: { r: 0, g: 0, b: 0, alpha: 0 } })
  .toBuffer();
await sharp(hero).resize(1200, 1500, { fit: "cover", position: "bottom" }).webp({ quality: 82, alphaQuality: 90, effort: 6 }).toFile(out("hero-4x5.webp"));

// 1:1 head-and-shoulders: square ~72% of the width, starting just above the hair.
const side = Math.round(width * 0.72);
await sharp(src)
  .extract({ left: Math.round((width - side) / 2), top: Math.round(height * 0.085), width: side, height: Math.min(side, height - Math.round(height * 0.085)) })
  .resize(800, 800, { fit: "cover", position: "top" })
  .webp({ quality: 82, alphaQuality: 90, effort: 6 })
  .toFile(out("about-1x1.webp"));

const og = await sharp(hero).resize(360, 450, { fit: "cover", position: "bottom" }).png({ compressionLevel: 9, palette: true, quality: 90 }).toBuffer();
await sharp(og).toFile(out("og-portrait.png"));
// Inlined for the OG image renderer: no filesystem reads at render time, so OG images prerender
// in every build mode (Vercel and static export).
writeFileSync(
  join(root, "src/components/seo/og-portrait.ts"),
  `// Generated by scripts/process-photo.mjs. Do not edit.\nexport const ogPortrait = "data:image/png;base64,${og.toString("base64")}";\n`,
);

console.log("Wrote hero-4x5.webp, about-1x1.webp, og-portrait.png, og-portrait.ts from", src);
