import { ArrowLeft, ArrowRight, ChevronRight } from "lucide-react";
import type { Metadata } from "next";
import { getTranslations } from "next-intl/server";
import { notFound } from "next/navigation";
import type { ReactNode } from "react";
import { Closing } from "@/components/sections/closing";
import { ProjectLink } from "@/components/sections/selected-work";
import { ogSize } from "@/components/seo/og";
import { ProjectJsonLd } from "@/components/seo/json-ld";
import { ArchitectureDiagram } from "@/components/ui/architecture-diagram";
import { BrowserFrame, PhoneFrame } from "@/components/ui/device-frames";
import { Chip, StatusPill, TodoMark } from "@/components/ui/primitives";
import { ProjectMedia } from "@/components/ui/project-media";
import { LocaleLink } from "@/i18n/link";
import type { Locale } from "@/i18n/routing";
import { formatRange, getProject, getProjects } from "@/lib/content";
import { projectMetadata } from "@/lib/metadata";
import { projectScreenshots } from "@/lib/project-images";
import { projects } from "@/lib/site";
import { SHOW_TODO, isTodo } from "@/lib/todo";

// English: generated by app/projects/[slug]/og-image.png/route.tsx. Arabic: committed PNGs (npm run og:ar).
const ogImagePath = (slug: string, locale: Locale) =>
  locale === "ar" ? `/images/og/ar/${slug}.png` : `/projects/${slug}/og-image.png`;

export function projectStaticParams() {
  return projects.map((p) => ({ slug: p.slug }));
}

export function projectPageMetadata(slug: string, locale: Locale): Metadata {
  return projectMetadata(slug, locale, { url: ogImagePath(slug, locale), ...ogSize });
}

/**
 * One case-study template for every project and both languages. Built to be scanned in 30 seconds:
 * the "At a glance" block answers problem / role / outcome / timeline / team / stack before any prose.
 */
export async function ProjectPage({ slug, locale }: { slug: string; locale: Locale }) {
  const project = getProject(slug, locale);
  if (!project) notFound();

  const t = await getTranslations("caseStudy");
  const all = getProjects(locale);
  const next = all[(all.findIndex((p) => p.slug === project.slug) + 1) % all.length];
  const screenshots = projectScreenshots(project);
  const c = project.case;
  const timelineUnknown = isTodo(project.timeline.startISO);
  const metricKnown = !isTodo(project.metric);

  // Rows whose whole value is a placeholder are left out of production builds (see lib/todo.ts).
  const glance: { key: string; label: string; value: ReactNode; placeholder?: boolean }[] = [
    { key: "problem", label: t("problem"), value: c.problem },
    { key: "role", label: t("role"), value: project.role },
    {
      key: "outcome",
      label: t("outcome"),
      value: (
        <>
          {metricKnown ? project.metric : project.outcome}
          {!metricKnown && <TodoMark className="ms-2">{project.metric}</TodoMark>}
        </>
      ),
    },
    {
      key: "timeline",
      label: t("timeline"),
      placeholder: timelineUnknown,
      value: timelineUnknown ? <TodoMark>TODO_DATE</TodoMark> : formatRange(project.timeline.startISO, project.timeline.endISO, locale, t("present")),
    },
    { key: "team", label: t("team"), placeholder: isTodo(c.team), value: isTodo(c.team) ? <TodoMark>{c.team}</TodoMark> : c.team },
  ].filter((row) => SHOW_TODO || !row.placeholder);

  return (
    <article>
      <ProjectJsonLd project={project} image={ogImagePath(project.slug, locale)} />

      <header className="container-page pt-6 pb-10 md:pt-10 md:pb-14">
        {/* Mirrors the BreadcrumbList in ProjectJsonLd. */}
        <nav aria-label={t("breadcrumbAria")}>
          <ol className="flex flex-wrap items-center gap-1 text-sm text-muted">
            <li>
              <LocaleLink href="/" className="-ms-2 inline-flex min-h-11 items-center rounded-control px-2 hover:text-fg">
                {t("home")}
              </LocaleLink>
            </li>
            <li aria-hidden="true">
              <ChevronRight size={14} className="rtl:-scale-x-100" />
            </li>
            <li>
              <LocaleLink href="/#work" className="inline-flex min-h-11 items-center rounded-control px-2 hover:text-fg">
                {t("work")}
              </LocaleLink>
            </li>
            <li aria-hidden="true">
              <ChevronRight size={14} className="rtl:-scale-x-100" />
            </li>
            <li>
              <span aria-current="page" className="inline-flex min-h-11 items-center px-2 text-fg">
                {project.title}
              </span>
            </li>
          </ol>
        </nav>

        <div className="mt-4 grid items-start gap-10 lg:grid-cols-[minmax(0,1fr)_minmax(0,30rem)] lg:gap-14">
          <div>
            <ul className="flex flex-wrap gap-1.5">
              {project.statuses.map((s) => (
                <li key={s.label + s.kind}>
                  <StatusPill status={s} />
                </li>
              ))}
            </ul>
            <h1 className="mt-5 text-display font-semibold">
              {project.title} <span className="text-muted">{project.titleAccent}</span>
            </h1>
            <p className="mt-4 max-w-[60ch] text-lg text-fg-2">{project.summary}</p>
            <div className="mt-6 flex flex-wrap gap-2">
              {project.links.map((link) => (
                <ProjectLink key={link.href} link={link} variant="secondary" />
              ))}
            </div>
          </div>
          <ProjectMedia project={project} preload sizes="(min-width: 1024px) 480px, calc(100vw - 32px)" />
        </div>
      </header>

      {/* TL;DR */}
      <section aria-labelledby="glance-title" className="border-y border-line bg-surface">
        <div className="container-page py-8 md:py-10">
          <h2 id="glance-title" className="kicker">
            {t("tldr")}
          </h2>
          <dl className="mt-5 grid gap-x-10 gap-y-6 md:grid-cols-2 lg:grid-cols-3">
            {glance.map((row) => (
              <div key={row.key} className={row.key === "problem" ? "md:col-span-2 lg:col-span-1 lg:row-span-2" : undefined}>
                <dt className="text-sm font-medium text-muted">{row.label}</dt>
                <dd className="mt-1 text-[0.9375rem] text-fg">{row.value}</dd>
              </div>
            ))}
            <div className="md:col-span-2">
              <dt className="text-sm font-medium text-muted">{t("stack")}</dt>
              <dd className="mt-2 grid gap-2">
                {project.stack.map((group) => (
                  <ul key={group.label} aria-label={t("stackAria", { label: group.label })} className="flex flex-wrap items-center gap-1.5">
                    {project.stack.length > 1 && (
                      <li className="me-1 text-xs text-muted">
                        <bdi>{group.label}</bdi>
                      </li>
                    )}
                    {group.items.map((item) => (
                      <li key={item}>
                        <Chip>{item}</Chip>
                      </li>
                    ))}
                  </ul>
                ))}
              </dd>
            </div>
          </dl>
        </div>
      </section>

      <div className="container-page grid gap-14 py-14 md:py-20">
        <Block id="context" title={t("context")}>
          <div className="prose-case max-w-[68ch]">
            {c.context.map((p) => (
              <p key={p}>{p}</p>
            ))}
          </div>
        </Block>

        <Block id="architecture" title={t("architecture")}>
          <p className="prose-case max-w-[68ch] text-fg-2">{c.architecture}</p>
          <div className="mt-6 max-w-3xl">
            <ArchitectureDiagram
              id={`arch-${project.slug}`}
              title={t("architectureTitle", { title: project.title })}
              architecture={project.architecture}
            />
          </div>
        </Block>

        <Block id="decisions" title={t("decisions")}>
          <ol className="grid gap-4 md:grid-cols-3">
            {c.decisions.map((d, i) => (
              <li key={d.title} className="card flex flex-col p-5">
                <span className="font-mono text-xs text-muted" dir="ltr">
                  {String(i + 1).padStart(2, "0")}
                </span>
                <h3 className="mt-2 font-semibold">{d.title}</h3>
                <p className="mt-2 text-[0.9375rem] text-fg-2">{d.why}</p>
                <div className="min-h-4 flex-1" aria-hidden="true" />
                <p className="border-t border-line pt-3 text-sm text-muted">
                  <span className="font-medium text-fg">{t("tradeoff")}</span> {d.tradeoff}
                </p>
              </li>
            ))}
          </ol>
        </Block>

        <div className="grid gap-14 md:grid-cols-2 md:gap-10">
          <Block id="challenges" title={t("challenges")}>
            <ul className="list-dash grid gap-3 text-fg-2">
              {c.challenges.map((x) => (
                <li key={x}>{x}</li>
              ))}
            </ul>
          </Block>
          <Block id="improve" title={t("improve")}>
            <ul className="list-dash grid gap-3 text-fg-2">
              {c.improve.map((x) => (
                <li key={x}>{x}</li>
              ))}
            </ul>
          </Block>
        </div>

        {screenshots.length > 0 && (
          <Block id="screenshots" title={t("screenshots")}>
            <ul className="grid items-start gap-4 sm:grid-cols-2 lg:grid-cols-3">
              {screenshots.map((s) => (
                <li key={s.src} className={s.device === "phone" ? "mx-auto w-full max-w-[220px]" : ""}>
                  {s.device === "phone" ? (
                    <PhoneFrame src={s.src} alt={s.alt} sizes="220px" />
                  ) : (
                    <BrowserFrame src={s.src} alt={s.alt} sizes="(min-width: 1024px) 352px, (min-width: 640px) 45vw, calc(100vw - 32px)" />
                  )}
                </li>
              ))}
            </ul>
          </Block>
        )}

        <Block id="links" title={t("links")}>
          {project.links.length > 0 ? (
            <div className="flex flex-wrap gap-2">
              {project.links.map((link) => (
                <ProjectLink key={link.href} link={link} variant="secondary" />
              ))}
            </div>
          ) : (
            <p className="text-fg-2">{t("noPublicLink")}</p>
          )}
        </Block>

        <nav aria-label={t("moreProjectsAria")} className="grid gap-4 border-t border-line pt-8 md:grid-cols-[auto_minmax(0,1fr)] md:items-center">
          <LocaleLink href="/#work" className="inline-flex min-h-11 items-center gap-2 text-sm text-muted hover:text-fg">
            <ArrowLeft size={16} className="rtl:-scale-x-100" aria-hidden="true" />
            {t("allProjects")}
          </LocaleLink>
          <LocaleLink
            href={`/projects/${next.slug}`}
            className="card group flex items-center justify-between gap-4 p-5 hover:border-line-strong md:justify-self-end md:min-w-[22rem]"
          >
            <span>
              <span className="kicker block">{t("nextProject")}</span>
              <span className="mt-1 block font-semibold text-fg">
                {next.title} <span className="text-muted">{next.titleAccent}</span>
              </span>
            </span>
            <ArrowRight size={18} className="shrink-0 text-muted group-hover:text-fg rtl:-scale-x-100" aria-hidden="true" />
          </LocaleLink>
        </nav>
      </div>

      <Closing />
    </article>
  );
}

function Block({ id, title, children }: { id: string; title: string; children: ReactNode }) {
  return (
    <section aria-labelledby={`${id}-title`}>
      <h2 id={`${id}-title`} className="mb-5 text-2xl font-semibold">
        {title}
      </h2>
      {children}
    </section>
  );
}
