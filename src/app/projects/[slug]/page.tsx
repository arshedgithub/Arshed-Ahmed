// Generated by ./og-image.png/route.tsx.
const ogImagePath = (slug: string) => `/projects/${slug}/og-image.png`;

export const dynamicParams = false;

export function generateStaticParams() {
  return projects.map((p) => ({ slug: p.slug }));
}

export async function generateMetadata({ params }: PageProps<"/projects/[slug]">): Promise<Metadata> {
  const { slug } = await params;
  const project = getProject(slug);
  if (!project) return {};
  const title = project.seoTitle;
  const description = project.seoDescription;
  const url = `/projects/${project.slug}`;
  const image = {
    url: ogImagePath(project.slug),
    ...ogSize,
    type: "image/png",
    alt: `${project.title} ${project.titleAccent ?? ""} case study by ${site.name}: ${project.subtitle}`.replace(/\s+/g, " "),
  };
  // openGraph replaces the root layout's object rather than merging it, so site-wide fields are repeated here.
  return {
    title,
    description,
    alternates: { canonical: url },
    openGraph: {
      type: "article",
      url,
      title,
      description,
      siteName: site.name,
      locale: "en_US",
      authors: [site.url],
      images: [image],
    },
    twitter: { card: "summary_large_image", title, description, images: [image] },
  };
}

export default async function ProjectPage({ params }: PageProps<"/projects/[slug]">) {
  const { slug } = await params;
  const project = getProject(slug);
  if (!project) notFound();

  const { default: Content } = await import(`@/content/projects/${project.slug}.mdx`);
  const index = projects.findIndex((p) => p.slug === project.slug);
  const next = projects[(index + 1) % projects.length];
  const screenshots = projectScreenshots(project);
  const heroShot = screenshots.find((s) => s.device === "browser") ?? projectCover(project);
  const heroPhone = screenshots.find((s) => s.device === "phone");

  return (
    <article className="pb-16 md:pb-24">
      <ProjectJsonLd project={project} image={ogImagePath(project.slug)} />

      <header className="border-b border-line">
        <div className="container-page grid items-center gap-8 py-8 md:py-14 lg:grid-cols-[minmax(0,1fr)_480px] lg:gap-12">
          <div>
            {/* Mirrors the BreadcrumbList in ProjectJsonLd. */}
            <nav aria-label="Breadcrumb">
              <ol className="flex flex-wrap items-center gap-1 text-sm text-muted">
                <li>
                  <Link href="/" className="-ml-2 inline-flex min-h-11 items-center rounded-lg px-2 hover:text-fg">
                    Home
                  </Link>
                </li>
                <li aria-hidden="true">
                  <ChevronRight size={14} />
                </li>
                <li>
                  <span aria-current="page" className="inline-flex min-h-11 items-center px-2 text-fg/90">
                    {project.title} {project.titleAccent}
                  </span>
                </li>
              </ol>
            </nav>
            <h1 className="mt-4 text-3xl font-bold tracking-tight md:text-5xl">
              {project.title} {project.titleAccent && <span className="text-accent">{project.titleAccent}</span>}
            </h1>
            <p className="mt-3 text-lg text-muted">{project.subtitle}</p>
            <p className="mt-3 max-w-xl text-muted">{project.summary}</p>
            <div className="mt-4 flex flex-wrap gap-2">
              <Chip>{project.tag}</Chip>
              {project.badges.map((b) => (
                <Chip key={b} className="border-accent/40 bg-accent-soft text-fg">{b}</Chip>
              ))}
              {project.period && <Chip>{project.period}</Chip>}
            </div>
          </div>
          {heroShot ? (
            <div className={heroPhone ? "relative pr-10 pb-6" : undefined}>
              <BrowserFrame src={heroShot.src} alt={heroShot.alt} sizes="(min-width: 1024px) 480px, calc(100vw - 32px)" preload />
              {heroPhone && (
                <PhoneFrame
                  src={heroPhone.src}
                  alt=""
                  sizes="110px"
                  className="absolute right-0 bottom-0 w-[22%] min-w-20 shadow-card"
                />
              )}
            </div>
          ) : (
            <ProjectFallback project={project} variant="hero" />
          )}
        </div>
      </header>

      <div className="container-page mt-10 md:mt-14">
        <div className="card mx-auto max-w-3xl bg-raised p-5 md:p-10">
          <div className="prose-case">
            <Content
              components={{
                Architecture: () => (
                  <ArchitectureDiagram
                    id={`arch-${project.slug}`}
                    title={`${project.title} system architecture`}
                    architecture={project.architecture}
                  />
                ),
                Stack: () => <StackList project={project} />,
                ProjectLinks: () => <ProjectLinks project={project} />,
              }}
            />
          </div>
        </div>

        {screenshots.length > 0 && (
          <section aria-labelledby="screenshots-title" className="mt-14">
            <h2 id="screenshots-title" className="text-xl font-semibold">
              Screenshots
            </h2>
            <ul className="mt-6 grid items-start gap-4 sm:grid-cols-2 lg:grid-cols-3">
              {screenshots.map((s) => (
                <li key={s.src} className={s.device === "phone" ? "mx-auto w-full max-w-[220px]" : ""}>
                  {s.device === "phone" ? (
                    <PhoneFrame src={s.src} alt={s.alt} sizes="220px" />
                  ) : (
                    <BrowserFrame src={s.src} alt={s.alt} sizes="(min-width: 1024px) 352px, (min-width: 640px) 45vw, calc(100vw - 32px)" />
                  )}
                </li>
              ))}
            </ul>
          </section>
        )}

        <nav aria-label="More projects" className="mt-14 flex flex-wrap items-center justify-between gap-4 border-t border-line pt-6">
          <Link href="/#work" className="inline-flex min-h-11 items-center gap-2 text-sm text-muted hover:text-fg">
            <ArrowLeft size={16} aria-hidden="true" />
            All projects
          </Link>
          <Link
            href={`/projects/${next.slug}`}
            className="inline-flex min-h-11 items-center gap-2 text-sm font-medium text-accent"
          >
            Next: {next.title} {next.titleAccent}
            <ArrowRight size={16} aria-hidden="true" />
          </Link>
        </nav>
      </div>
    </article>
  );
}

function StackList({ project }: { project: Project }) {
  return (
    <div className="mt-4 grid gap-4">
      {project.stack.map((group) => (
        <div key={group.label}>
          {project.stack.length > 1 && <p className="mb-2 font-mono text-xs uppercase tracking-wider text-muted">{group.label}</p>}
          <ul className="flex flex-wrap gap-2" aria-label={`${group.label} stack`}>
            {group.items.map((item) => (
              <li key={item}>
                <Chip>{item}</Chip>
              </li>
            ))}
          </ul>
        </div>
      ))}
    </div>
  );
}

function ProjectLinks({ project }: { project: Project }) {
  if (project.links.length === 0) {
    // TODO: confirm wording, or add links in site.ts.
    return <p>This project has no public link. I am happy to walk through it in an interview.</p>;
  }
  return (
    <div className="mt-4 flex flex-wrap gap-3">
      {project.links.map((link) => (
        <a
          key={link.href}
          href={link.href}
          target="_blank"
          rel="noopener noreferrer"
          className={buttonClasses(link.kind === "live" ? "primary" : "secondary")}
        >
          {link.kind === "github" && <GitHubIcon size={16} />}
          {link.label}
          <ArrowUpRight size={16} aria-hidden="true" />
          <span className="sr-only"> (opens in a new tab)</span>
        </a>
      ))}
    </div>
  );
}
